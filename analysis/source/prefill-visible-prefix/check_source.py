"""CPU source/inequality contract only; no Torch/Triton/kernel simulation."""
import ast
import copy
import hashlib
import importlib.util
from pathlib import Path


ROOT = Path(__file__).resolve().parents[3]
path = ROOT / "patches/framework/biv150_prefill_visible_prefix.py"
spec = importlib.util.spec_from_file_location("visible_prefix_source_contract", path)
policy = importlib.util.module_from_spec(spec)
spec.loader.exec_module(policy)
base = ROOT / "experiments/official/20261021T092944Z-sql-mixed-official/source/installed/vllm/v1/attention"
source = (base / "ops/triton_unified_attention.py").read_bytes()
helpers = (base / "ops/triton_attention_helpers.py").read_bytes()
assert hashlib.sha256((base / "backends/triton_attn.py").read_bytes()).hexdigest() == policy.EXPECTED_BACKEND
changed = policy.transform_source(source, helpers)
saved = Path(__file__).with_name("triton_unified_attention_visible_prefix.py")
assert saved.read_bytes() == changed
original_ast, changed_ast = ast.parse(source), ast.parse(changed)
assert len(original_ast.body) == len(changed_ast.body)
for a, b in zip(original_ast.body, changed_ast.body):
    if isinstance(a, ast.FunctionDef) and a.name == "kernel_unified_attention":
        original_kernel, changed_kernel = a, b
    else:
        assert ast.dump(a) == ast.dump(b), "non-kernel module AST changed"
signature = copy.deepcopy(changed_kernel.args)
assert signature.args.pop().arg == "BIV150_VISIBLE_PREFIX"
assert ast.literal_eval(signature.defaults.pop()) is False
assert ast.dump(signature) == ast.dump(original_kernel.args)
for call in ("tl.dot", "softmax_step", "_cast_kv_tile", "apply_softcap", "apply_alibi_to_score", "load_qq_bias_tile"):
    def expressions(kernel):
        return [ast.dump(x) for x in ast.walk(kernel) if isinstance(x, ast.Call)
                and ast.unparse(x.func) == call]
    assert expressions(original_kernel) == expressions(changed_kernel), "FP expression changed: " + call
assert changed.count(b"    for j in range(loop_lo, loop_hi):\n") == 1
assert b"    if q_block_local_idx * BLOCK_Q >= cur_batch_query_len:\n        return\n" in changed
for bad_source, bad_helpers in ((source + b"\n", helpers), (source, helpers + b"\n")):
    try:
        policy.transform_source(bad_source, bad_helpers)
    except RuntimeError:
        pass
    else:
        raise AssertionError("modified source was accepted")
checks = 0
for length in (0, 1, 15, 16, 17, 2019, 2048):
    for context in (-1, 0, 1, 15, 16, 63, 64, 14365):
        seq_len = context + length
        for local in range(-1, (length + 15) // 16 + 1):
            first = local * 16
            complete = local >= 0 and first >= 0 and first + 16 <= length and context >= 0
            loop_hi = (min(context + first + 16, seq_len) + 63) // 64
            full = min(loop_hi, max(0, (context + first + 1) // 64)) if complete else 0
            if not complete:
                assert full == 0
            for tile in range(max(0, full)):
                assert (tile + 1) * 64 - 1 <= context + first <= seq_len - 1
                assert first + 15 < length
                checks += 1
compile(changed, str(saved), "exec")
compile(path.read_bytes(), str(path), "exec")
print("exact inputs, backend pin, source rejection and archived generated bytes: PASS")
print("non-kernel AST, original signature, FP call ASTs, one tile loop and early-return: PASS")
print("full/partial/invalid query and unaligned-prefix inequality: PASS", checks)
print("generated_sha256", hashlib.sha256(changed).hexdigest())
print("runtime_sha256", hashlib.sha256(path.read_bytes()).hexdigest())
print("CPU source/arithmetic only; no CUDA compile, bitwise or performance conclusion")
